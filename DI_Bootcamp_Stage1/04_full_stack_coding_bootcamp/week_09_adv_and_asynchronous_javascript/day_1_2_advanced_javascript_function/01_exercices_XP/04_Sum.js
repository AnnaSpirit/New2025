// Arrow function en une ligne pour additionner deux nombres
const add = (a, b) => a + b;

// Exemples
console.log(add(3, 7));   // 10  
console.log(add(-2, 5));  // 3


// Explications
// La syntaxe(a, b) => a + b fait tout en une seule ligne, clairement lisible.

// Pas besoin de return, l’expression est retournée automatiquement.